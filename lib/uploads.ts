import "server-only";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { supabaseEnv } from "./supabase/env";

// ---------- storage: one private Supabase Storage bucket (db/init/012_storage.sql) ----------
// The secret key bypasses Storage policies, so this runs on the server only and every read goes through an
// /api/* route that checks the app's own session + role first. Never expose the key (no NEXT_PUBLIC_).
export type Carpeta = "comprobantes" | "grupos" | "avatares";
const BUCKET = "archivos";
let cliente: SupabaseClient | undefined;
function bucket() {
  const clave = process.env.SUPABASE_SECRET_KEY;
  if (!clave) throw new Error("Falta SUPABASE_SECRET_KEY");
  cliente ??= createClient(supabaseEnv().url, clave, {
    auth: { persistSession: false, autoRefreshToken: false }, // a server key, not a user session
  });
  return cliente.storage.from(BUCKET);
}

// names are generated by the server (`<pedido>-<ms>.<ext>`, `<uuid>.<ext>`), never taken from the client
export async function guardar(carpeta: Carpeta, nombre: string, buf: Buffer) {
  const { error } = await bucket().upload(`${carpeta}/${nombre}`, buf, {
    contentType: MIME[nombre.split(".").pop() ?? ""],
    upsert: false,
  });
  if (error) throw error;
}

// null when it doesn't exist (the caller answers 404)
export async function leer(carpeta: Carpeta, nombre: string) {
  const { data, error } = await bucket().download(`${carpeta}/${nombre}`);
  return error ? null : Buffer.from(await data.arrayBuffer());
}

// best effort: a leftover file costs a few KB, a failed delete must not fail the user's save
export async function borrar(carpeta: Carpeta, nombre: string) {
  await bucket()
    .remove([`${carpeta}/${nombre}`])
    .catch(() => {});
}

export const TIPOS: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "application/pdf": "pdf",
};
export const MIME: Record<string, string> = Object.fromEntries(
  Object.entries(TIPOS).map(([m, e]) => [e, m]),
);

// profile/group pictures: JPG, PNG or WEBP only (never SVG, which can carry scripts)
export const IMAGENES: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
};
export const MIME_IMAGEN: Record<string, string> = Object.fromEntries(
  Object.entries(IMAGENES).map(([m, e]) => [e, m]),
);
// the browser's file.type is client-controlled: the first bytes must agree with it
const FIRMAS: Record<string, (b: Buffer) => boolean> = {
  jpg: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff,
  png: (b) =>
    b.subarray(0, 8).equals(Buffer.from("\x89PNG\r\n\x1a\n", "latin1")),
  webp: (b) =>
    b.toString("latin1", 0, 4) === "RIFF" &&
    b.toString("latin1", 8, 12) === "WEBP",
  pdf: (b) => b.toString("latin1", 0, 5) === "%PDF-",
};
export const firmaOk = (ext: string, buf: Buffer) => !!FIRMAS[ext]?.(buf);

export type Imagen = { ext: string; buf: Buffer };
// null: nothing was sent; { error }: sent but rejected
export async function leerImagen(
  f: FormData,
  campo: string,
  maxMb: number,
): Promise<Imagen | { error: string } | null> {
  const file = f.get(campo);
  if (!(file instanceof File) || file.size === 0) return null;
  const ext = IMAGENES[file.type];
  if (!ext) return { error: "La imagen debe ser JPG, PNG o WEBP" };
  if (file.size > maxMb * 1024 * 1024)
    return { error: `La imagen supera ${maxMb} MB` };
  const buf = Buffer.from(await file.arrayBuffer());
  if (!firmaOk(ext, buf))
    return { error: "El archivo no es una imagen válida" };
  return { ext, buf };
}
